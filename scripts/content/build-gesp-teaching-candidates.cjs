const lessons = [];
function add(suffix, explanation, example, check, debug, transfer, retention) {
  const atomId = 'gesp-cpp.' + suffix, atom = knowledge.atoms.find(row => row.id === atomId), task = tasks.find(row => row.atomId === atomId);
  if (!atom || !task || lessons.some(row => row.atomId === atomId)) throw Error('Unknown or duplicate teaching target');
  const activity = ([prompt, referenceAnswer]) => ({ prompt, referenceAnswer, scoring: 'human_review_required' });
  lessons.push({ id: 'gesp-teaching-' + suffix.replaceAll('.', '-'), atomId, level: atom.level, title: atom.name,
    goal: atom.successCriterion, prerequisiteIds: atom.prerequisiteIds, sourceEvidence: atom.sourceEvidence,
    status: 'editorial_candidate', linkedTaskId: task.id,
    linkedTaskContentSha256: crypto.createHash('sha256').update(JSON.stringify(task)).digest('hex'),
    explanation, example: activity(example), check: activity(check), debug: activity(debug),
    transfer: activity(transfer), retention: activity(retention) });
}
