export function buildChemistryCurriculum(): FoundationDefinition[] {
  return points.map(p => {
    const unit = chemistryUnits.find(unit => (unit.codes as readonly string[]).includes(p.code))!;
    const teaching: AtomTeaching = { reviewStatus: 'approved', explanation: p.explanation,
      example: { prompt: p.example[0], steps: [...p.example[1]], conclusion: p.example[2] },
      commonErrors: [{ code: `chemistry:${p.code}:contrast`, observation: p.error,
        alternativeExplanations: ['可能混淆了概念、适用条件或关键证据，需要用对照任务核查。', '也可能是读题、符号或计算记录出现遗漏，不能仅凭一道错题认定原因。'], verification: p.verification }],
      verification: { understanding: `撤去例题，让学生用自己的话说明“${p.name}”的判断依据，再做一道新的概念对照题。`,
        procedure: `使用未展示过的题目，独立完成“${p.objective}”，保留首次作答及必要步骤。`,
        transfer: p.verification,
        retention: '按1、3、7、14天安排到期复测，使用未展示的新题；独立完成、提示后完成和看过答案的订正分别记录。' } };
    const contrast = numericContrasts[p.code];
    const exercises = contrast
      ? [...Array.from({ length: 48 }, (_, n) => p.probe(n)), ...Array.from({ length: contrast.length * 6 }, (_, n) => facts(contrast, contrast.map(x=>x[1]))(n))]
      : Array.from({ length: 72 }, (_, n) => p.probe(n));
    return { atom: { id: chemistryAtomId(p.code), subject: 'chemistry', grade: 9, term: 'upper', name: p.name,
      strand: unit.title, objective: p.objective, successCriterion: `能独立${p.objective}，至少用两个不同题族核对，再补迁移及真实间隔证据`,
      prerequisiteIds: p.prerequisites.map(chemistryAtomId), curriculumVersion: CHEMISTRY_VERSION, status: 'published', version: 1, teaching }, exercises };
  });
}
