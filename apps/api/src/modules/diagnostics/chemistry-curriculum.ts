// The four prompts demand different operations on a case. Family identities retain
// the operation; a changed question ID alone never proves a new structure or mastery.
function facts(cases: readonly Fact[], alternatives: readonly string[]): Probe {
  return n => {
    const [situation, answer, reason] = cases[n % cases.length];
    const form = Math.floor(n / cases.length) % 6;
    const choices = [...new Set(alternatives)];
    const wrong = choices.find(value => value !== answer)!;
    const asserted = n % 2 === 0 ? answer : wrong;
    const other = cases[(n + 5) % cases.length];
    const pair = `${answer}；${other[1]}`;
    const shapes = [
      [`${situation}。请选择正确判断。`, answer, choices],
      [`同学把“${situation}”判断为“${asserted}”。这一判断是否正确？`, asserted === answer ? '正确' : '不正确', ['正确', '不正确']],
      [`${situation}。哪项依据能支持正确判断？`, reason, [reason, `仅凭名称或外观就认定为“${wrong}”`, '没有条件也可以推广到所有情形']],
      [`比较两条记录：①${situation}；②${other[0]}。按①②顺序，哪组判断均符合条件？`, pair, [pair, `${wrong}；${other[1]}`, `${answer}；无法根据任何条件判断`]],
      [`记录①：${situation}；记录②：${other[0]}。有人把①的判断“${answer}”直接推广到②。对照②的条件，这一推广是否成立？`, other[1] === answer ? '成立' : '不成立', ['成立', '不成立']],
      [`需要纠正一份记录中对“${situation}”的解释。下列哪条表述保留了给定条件？`, `${answer}，因为${reason}`, [`${answer}，因为${reason}`, `${wrong}，不需要核对理由`, `所有情形都必定是${wrong}`]],
    ] as const;
    const [stem, expected, options] = shapes[form];
    return { stem, answer: expected, mode: 'single_choice', options: [...options], analysis: reason,
      dimension: form === 2 || form === 4 ? 'transfer' : form === 1 || form === 5 ? 'procedure' : 'understanding', family: `case-${['classify', 'contrast', 'evidence', 'compare-pair', 'link-evidence', 'correct-explanation'][form]}`,
      expectedSeconds: 65, identityVersion: 2 };
  };
}
function numeric(stem: string, answer: number, analysis: string, n: number, family: string): Exercise {
  return { stem, answer, mode: 'numeric_blank', analysis, family,
    dimension: n % 3 === 0 ? 'understanding' : n % 3 === 1 ? 'procedure' : 'transfer', expectedSeconds: 90, identityVersion: 2 };
}
